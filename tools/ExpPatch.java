import com.sun.javacard.exportfile.EfClass;
import com.sun.javacard.exportfile.EfExportFile;
import com.sun.javacard.exportfile.EfMethod;

import java.io.BufferedInputStream;
import java.io.BufferedOutputStream;
import java.io.DataInputStream;
import java.io.DataOutputStream;
import java.io.FileInputStream;
import java.io.FileOutputStream;
import java.util.Arrays;
import java.util.Comparator;

/**
 * Rewrites the stub JOPX export file so that its class and method tokens match the tokens that
 * the original {@code Curve25519.cap} links against.
 *
 * <p>The converter assigns tokens on its own (interfaces first, then classes, then methods in
 * declaration order), which cannot produce the layout the card expects: JCOPX puts the
 * operations class at class token 1 with method tokens 2, 3 and 13, the key interfaces at 9 and
 * 10, and the key factory at 11. Because a CAP file links purely by token, only the tokens
 * matter, so the stub exp is generated by the converter and then patched here.
 *
 * <p>Usage: {@code ExpPatch <in.exp> <out.exp>}
 */
public final class ExpPatch {

    private static final String JCOPX_PRIVATE_KEY = "jopx/JcopxPrivateKey";
    private static final String JCOPX_PUBLIC_KEY = "jopx/JcopxPublicKey";
    private static final String JCOPX_CURVE25519 = "jopx/JcopxCurve25519";
    private static final String JCOPX_KEY_FACTORY = "jopx/JcopxKeyFactory";

    private ExpPatch() {
    }

    public static void main(String[] args) throws Exception {
        if (args.length != 2) {
            System.err.println("usage: ExpPatch <in.exp> <out.exp>");
            System.exit(1);
        }

        EfExportFile exportFile = load(args[0]);

        EfClass privateKey = findClass(exportFile, JCOPX_PRIVATE_KEY);
        EfClass publicKey = findClass(exportFile, JCOPX_PUBLIC_KEY);
        EfClass curve25519 = findClass(exportFile, JCOPX_CURVE25519);
        EfClass keyFactory = findClass(exportFile, JCOPX_KEY_FACTORY);

        // Class tokens, as observed in the ConstantPool of the original CAP.
        privateKey.setClassToken(9);
        publicKey.setClassToken(10);
        curve25519.setClassToken(1);
        keyFactory.setClassToken(11);

        // Method tokens, as observed in the ConstantPool / Method component of the original CAP.
        setMethodToken(curve25519, "sign", "(L" + JCOPX_PRIVATE_KEY + ";B[BSS[BS)S", 2);
        setMethodToken(curve25519, "verify", "(L" + JCOPX_PUBLIC_KEY + ";B[BSS[BSS)S", 3);
        setMethodToken(curve25519, "keyAgreement",
                "(L" + JCOPX_PRIVATE_KEY + ";L" + JCOPX_PUBLIC_KEY + ";B[BS)S", 13);
        setMethodToken(keyFactory, "createKey", "(BB)Ljava/lang/Object;", 1);
        setMethodToken(keyFactory, "genKeyPair",
                "(L" + JCOPX_PRIVATE_KEY + ";L" + JCOPX_PUBLIC_KEY + ";)V", 2);

        // The class table of the exp file is written in array order, so sort it by token.
        EfClass[] classes = exportFile.getClasses();
        Arrays.sort(classes, new Comparator<EfClass>() {
            public int compare(EfClass a, EfClass b) {
                return a.getClassToken() - b.getClassToken();
            }
        });

        dump(exportFile);

        DataOutputStream out = new DataOutputStream(
                new BufferedOutputStream(new FileOutputStream(args[1])));
        try {
            exportFile.toBinary(out);
        } finally {
            out.close();
        }
        System.out.println("wrote " + args[1]);
    }

    private static EfExportFile load(String path) throws Exception {
        EfExportFile exportFile = new EfExportFile();
        DataInputStream in = new DataInputStream(
                new BufferedInputStream(new FileInputStream(path)));
        try {
            exportFile.parse(in);
        } finally {
            in.close();
        }
        exportFile.resolve();
        return exportFile;
    }

    private static EfClass findClass(EfExportFile exportFile, String name) {
        for (EfClass c : exportFile.getClasses()) {
            if (c.getClassName().equals(name)) {
                return c;
            }
        }
        throw new IllegalArgumentException("class not found in export file: " + name);
    }

    private static void setMethodToken(EfClass clazz, String name, String descriptor, int token) {
        for (EfMethod m : clazz.getMethods()) {
            if (m.getMethodName().equals(name) && m.getMethodDescriptor().equals(descriptor)) {
                m.setMethodToken(token);
                System.out.println("  " + clazz.getClassName() + "." + name + descriptor
                        + " -> class token " + clazz.getClassToken() + ", method token " + token);
                return;
            }
        }
        throw new IllegalArgumentException(
                "method not found in export file: " + clazz.getClassName() + "." + name + descriptor);
    }

    private static void dump(EfExportFile exportFile) {
        System.out.println("export file " + exportFile.getClass().getSimpleName()
                + " magic=" + Integer.toHexString(exportFile.getMagic())
                + " version=" + exportFile.getMajorVersion() + "." + exportFile.getMinorVersion());
        for (EfClass c : exportFile.getClasses()) {
            System.out.println("  class token " + c.getClassToken() + " " + c.getClassName()
                    + " flags=0x" + Integer.toHexString(c.getAccessFlags()));
            for (EfMethod m : c.getMethods()) {
                System.out.println("    method token " + m.getMethodToken() + " "
                        + m.getMethodName() + m.getMethodDescriptor());
            }
        }
    }
}
